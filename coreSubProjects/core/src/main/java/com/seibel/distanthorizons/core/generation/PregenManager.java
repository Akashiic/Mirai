/**
 * Server-side LOD pregeneration (<code>/dh pregen</code>). <br>
 * While a run is active its level reports {@link #isRunningFor} so the world-generation queue is started
 * for that level only, even when distant generation is disabled in the config. Client generation requests
 * stay governed by the config/session (see <code>FullDataSourceRequestHandler</code>).
 */
public class PregenManager
{
	protected static final DhLogger LOGGER = new DhLoggerBuilder().build();

	/** Rollback switch: <code>-Dakashic.mirai.serverPregen=false</code> refuses every pregen start. */
	public static final String ENABLED_PROPERTY = "akashic.mirai.serverPregen";
	/** Submission pauses while the mean server tick is above this many ms (<= 0 disables). */
	public static final String MAX_TICK_MS_PROPERTY = "akashic.mirai.pregenMaxTickMs";
	public static final double DEFAULT_MAX_TICK_MS = 45.0;
	public static final String PROGRESS_FILE_NAME = "mirai-pregen-progress.properties";

	private static final long PUMP_INTERVAL_MS = 250;
	private static final long LOG_INTERVAL_MS = 30_000;

	public enum EPregenMode
	{
		/** only sections whose chunks (plus the 1-chunk border the generator loads) are already saved; never creates terrain */
		EXISTING,
		/** upstream behaviour: missing chunks are generated by the world generator */
		GENERATE;

		@Nullable
		public static EPregenMode parse(String name)
		{
			for (EPregenMode mode : values())
			{
				if (mode.name().equalsIgnoreCase(name))
				{
					return mode;
				}
			}
			return null;
		}
	}

	/** Answers whether chunks are saved on disk. Bound by the loader; null means {@link EPregenMode#EXISTING} is unsupported. */
	public interface ISavedChunkIndex
	{
		/** true when every chunk in the square [minChunkX, minChunkX + width) x [minChunkZ, minChunkZ + width) is saved */
		boolean allChunksSaved(IServerLevelWrapper level, int minChunkX, int minChunkZ, int width) throws IOException;
	}

	@Nullable
	public static volatile ISavedChunkIndex savedChunkIndex = null;
	/** mean server tick time in ms, bound by the loader; 0 when unknown */
	public static volatile DoubleSupplier serverTickMs = () -> 0;


	private final AtomicReference<RunningPregen> running = new AtomicReference<>();



	//=========//
	// running //
	//=========//

	/** Upstream signature, kept for the newer-MC command path. */
	public CompletableFuture<Void> startPregen(IServerLevelWrapper levelWrapper, DhBlockPos2D origin, int chunkRadius)
	{
		try
		{
			return this.start(levelWrapper, origin, chunkRadius, EPregenMode.GENERATE).task;
		}
		catch (IllegalArgumentException | IllegalStateException e)
		{
			CompletableFuture<Void> failed = new CompletableFuture<>();
			failed.completeExceptionally(e);
			return failed;
		}
	}

	/**
	 * @return a description of the started run, including whether it resumed saved progress
	 * @throws IllegalArgumentException/IllegalStateException with a user-facing message when the run cannot start
	 */
	public RunningPregen start(IServerLevelWrapper levelWrapper, DhBlockPos2D origin, int chunkRadius, EPregenMode mode)
	{
		if (!Boolean.parseBoolean(System.getProperty(ENABLED_PROPERTY, "true")))
		{
			throw new IllegalStateException("Pregen is disabled on this server (-D" + ENABLED_PROPERTY + "=false).");
		}
		if (chunkRadius < 1)
		{
			throw new IllegalArgumentException("chunkRadius must be at least 1.");
		}
		if (mode == EPregenMode.EXISTING && savedChunkIndex == null)
		{
			throw new IllegalStateException("Mode 'existing' is not supported on this Minecraft version; use 'generate'.");
		}

		IDhServerWorld world = SharedApi.tryGetDhServerWorld();
		IDhLevel level = world == null ? null : world.getLevel(levelWrapper);
		if (level == null || !(level.getFullDataProvider() instanceof GeneratedFullDataSourceProvider))
		{
			throw new IllegalStateException("Distant Horizons is not active for this dimension.");
		}
		GeneratedFullDataSourceProvider provider = (GeneratedFullDataSourceProvider) level.getFullDataProvider();

		long originSectionPos = DhSectionPos.convertToDetailLevel(
			DhSectionPos.encode(LodUtil.BLOCK_DETAIL_LEVEL, origin.x, origin.z),
			DhSectionPos.SECTION_MINIMUM_DETAIL_LEVEL);
		int sectionCount = PregenTask.sectionCountForChunkRadius(chunkRadius);

		File progressFile = new File(level.getSaveStructure().getSaveFolder(levelWrapper), PROGRESS_FILE_NAME);
		Properties runKey = progressKey(originSectionPos, chunkRadius, mode);
		int startIndex = readResumeIndex(progressFile, runKey);

		RunningPregen run = new RunningPregen(levelWrapper, mode, progressFile, runKey, startIndex);
		if (!this.running.compareAndSet(null, run))
		{
			throw new IllegalStateException("Pregen is already running.");
		}

		try
		{
			run.begin(new LevelTarget(provider, levelWrapper, mode), originSectionPos, sectionCount);
		}
		catch (RuntimeException e)
		{
			this.running.compareAndSet(run, null);
			throw e;
		}
		run.task.whenComplete((result, throwable) -> this.running.compareAndSet(run, null));
		return run;
	}

	@Nullable
	public CompletableFuture<Void> getRunningPregen()
	{
		RunningPregen run = this.running.get();
		return run == null ? null : run.task;
	}

	public boolean isRunningFor(IServerLevelWrapper levelWrapper)
	{
		RunningPregen run = this.running.get();
		return run != null && run.levelWrapper == levelWrapper && !run.task.isDone();
	}

	/** cancels the running pregen if it belongs to the given level (used when the level unloads) */
	public void cancelFor(IServerLevelWrapper levelWrapper)
	{
		RunningPregen run = this.running.get();
		if (run != null && run.levelWrapper == levelWrapper)
		{
			run.task.cancel(true);
		}
	}

	@Nullable
	public String getStatusString()
	{
		RunningPregen run = this.running.get();
		return run == null ? null : run.getStatusString();
	}



	//==========//
	// progress //
	//==========//

	private static Properties progressKey(long originSectionPos, int chunkRadius, EPregenMode mode)
	{
		Properties key = new Properties();
		key.setProperty("originX", Integer.toString(DhSectionPos.getX(originSectionPos)));
		key.setProperty("originZ", Integer.toString(DhSectionPos.getZ(originSectionPos)));
		key.setProperty("chunkRadius", Integer.toString(chunkRadius));
		key.setProperty("mode", mode.name());
		return key;
	}

	/** @return the saved index when the file belongs to exactly this run, otherwise 0 */
	private static int readResumeIndex(File progressFile, Properties runKey)
	{
		if (!progressFile.isFile())
		{
			return 0;
		}

		Properties saved = new Properties();
		try (InputStream in = new FileInputStream(progressFile))
		{
			saved.load(in);
			for (String name : runKey.stringPropertyNames())
			{
				if (!runKey.getProperty(name).equals(saved.getProperty(name)))
				{
					return 0;
				}
			}
			return Math.max(0, Integer.parseInt(saved.getProperty("nextIndex", "0")));
		}
		catch (IOException | NumberFormatException e)
		{
			LOGGER.warn("Ignoring unreadable pregen progress file [" + progressFile + "]: " + e.getMessage());
			return 0;
		}
	}



	//================//
	// helper classes //
	//================//

	public static final class RunningPregen
	{
		public final IServerLevelWrapper levelWrapper;
		public final EPregenMode mode;
		public final int resumedFromIndex;

		private final File progressFile;
		private final Properties runKey;
		private final AtomicInteger checkpointIndex = new AtomicInteger();
		private volatile int savedCheckpointIndex = -1;
		private final ScheduledExecutorService scheduler;

		public PregenTask task;
		private long lastLogMs;


		private RunningPregen(IServerLevelWrapper levelWrapper, EPregenMode mode, File progressFile, Properties runKey, int resumedFromIndex)
		{
			this.levelWrapper = levelWrapper;
			this.mode = mode;
			this.progressFile = progressFile;
			this.runKey = runKey;
			this.resumedFromIndex = resumedFromIndex;
			this.checkpointIndex.set(resumedFromIndex);
			this.scheduler = Executors.newSingleThreadScheduledExecutor(runnable ->
			{
				Thread thread = new Thread(runnable, "DH Pregen [" + levelWrapper.getDhIdentifier() + "]");
				thread.setDaemon(true);
				return thread;
			});
		}

		private void begin(PregenTask.ITarget target, long originSectionPos, int sectionCount)
		{
			PregenTask.Settings settings = new PregenTask.Settings();
			settings.maxInFlight = Config.Common.MultiThreading.numberOfThreads::get;
			settings.serverTickMs = () -> serverTickMs.getAsDouble();
			settings.maxServerTickMs = readMaxTickMs();
			settings.checkpoint = this.checkpointIndex::set;
			settings.wakeUp = () ->
			{
				try { this.scheduler.execute(this::pumpSafely); }
				catch (RejectedExecutionException ignore) { /* the run is over */ }
			};

			this.task = new PregenTask(target, settings, originSectionPos, sectionCount, this.resumedFromIndex);
			this.task.whenComplete((result, throwable) -> this.onFinished(throwable));
			this.lastLogMs = System.currentTimeMillis();
			this.scheduler.scheduleWithFixedDelay(this::pumpSafely, 0, PUMP_INTERVAL_MS, TimeUnit.MILLISECONDS);
		}

		private void pumpSafely()
		{
			try
			{
				this.task.pump();
				this.saveCheckpoint(false);
				long now = System.currentTimeMillis();
				if (now - this.lastLogMs >= LOG_INTERVAL_MS && !this.task.isDone())
				{
					this.lastLogMs = now;
					LOGGER.info(this.getStatusString());
				}
			}
			catch (RuntimeException e)
			{
				LOGGER.error("Pregen failed unexpectedly", e);
				this.task.completeExceptionally(e);
			}
		}

		private void onFinished(@Nullable Throwable throwable)
		{
			this.scheduler.shutdownNow();
			if (throwable == null)
			{
				if (this.progressFile.exists() && !this.progressFile.delete())
				{
					LOGGER.warn("Unable to delete finished pregen progress file [" + this.progressFile + "].");
				}
				LOGGER.info("Pregen complete: " + this.task.getCountersString());
			}
			else
			{
				this.saveCheckpoint(true);
				LOGGER.info("Pregen stopped (" + throwable.getClass().getSimpleName() + "); restart it with the same arguments to resume. " + this.task.getCountersString());
			}
		}

		private synchronized void saveCheckpoint(boolean force)
		{
			int index = this.checkpointIndex.get();
			if (!force && index == this.savedCheckpointIndex)
			{
				return;
			}

			Properties saved = new Properties();
			saved.putAll(this.runKey);
			saved.setProperty("nextIndex", Integer.toString(index));
			try (OutputStream out = new FileOutputStream(this.progressFile))
			{
				saved.store(out, "Mirai pregen progress; deleted when the run completes");
				this.savedCheckpointIndex = index;
			}
			catch (IOException e)
			{
				LOGGER.warn("Unable to save pregen progress to [" + this.progressFile + "]: " + e.getMessage());
			}
		}

		public String getStatusString()
		{
			return "Pregen [" + this.mode.name().toLowerCase() + "] " + this.levelWrapper.getDhIdentifier() + ": " + this.task.getCountersString();
		}

		private static double readMaxTickMs()
		{
			try { return Double.parseDouble(System.getProperty(MAX_TICK_MS_PROPERTY, Double.toString(DEFAULT_MAX_TICK_MS))); }
			catch (NumberFormatException e) { return DEFAULT_MAX_TICK_MS; }
		}
	}

	/** Adapts the level's data source provider; owns and closes every data source it reads. */
	private static final class LevelTarget implements PregenTask.ITarget
	{
		private final GeneratedFullDataSourceProvider provider;
		private final IServerLevelWrapper levelWrapper;
		private final EPregenMode mode;

		LevelTarget(GeneratedFullDataSourceProvider provider, IServerLevelWrapper levelWrapper, EPregenMode mode)
		{
			this.provider = provider;
			this.levelWrapper = levelWrapper;
			this.mode = mode;
		}

		@Override
		public boolean shouldSkip(long sectionPos)
		{
			ISavedChunkIndex index = savedChunkIndex;
			if (this.mode != EPregenMode.EXISTING || index == null)
			{
				return false;
			}

			// the generator also loads the 1-chunk border around every chunk it converts
			int width = DhSectionPos.getChunkWidth(sectionPos);
			int minChunkX = Math.floorDiv(DhSectionPos.getMinCornerBlockX(sectionPos), LodUtil.CHUNK_WIDTH) - 1;
			int minChunkZ = Math.floorDiv(DhSectionPos.getMinCornerBlockZ(sectionPos), LodUtil.CHUNK_WIDTH) - 1;
			try
			{
				return !index.allChunksSaved(this.levelWrapper, minChunkX, minChunkZ, width + 2);
			}
			catch (IOException e)
			{
				LOGGER.warn("Unable to read saved chunks for section " + DhSectionPos.toString(sectionPos) + "; skipping it: " + e.getMessage());
				return true;
			}
		}

		@Override
		public CompletableFuture<Boolean> isFullyGenerated(long sectionPos)
		{
			return this.provider.getAsync(sectionPos).thenApply((FullDataSourceV2 dataSource) ->
			{
				if (dataSource == null)
				{
					return false;
				}
				try
				{
					return this.provider.generationStepsAreFullyGenerated(dataSource.columnGenerationSteps);
				}
				finally
				{
					dataSource.close();
				}
			});
		}

		@Nullable
		@Override
		public CompletableFuture<?> queueGeneration(long sectionPos)
		{ return this.provider.queuePositionForRetrieval(sectionPos); }
	}

}
